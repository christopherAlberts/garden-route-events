"""South African public holidays -> data/holidays.json + data/holidays.js.

Dates are copied from the official list at https://www.gov.za/about-sa/public-holidays
(2026 and 2027 are published there) plus any one-off days declared under section 2A of the
Public Holidays Act. Never add a year that gov.za hasn't published (Easter dates move).
The Act's Sunday rule (a holiday on a Sunday makes the following Monday a public holiday)
is applied automatically; observed days already listed by gov.za are not duplicated.
"""
import datetime as dt, json, os
GOV = "https://www.gov.za/about-sa/public-holidays"
ACT = "Public Holidays Act 36 of 1994, s2(1): a holiday on a Sunday moves to the Monday"
BASE = {  # verified against gov.za on 18 Oct 2026
 2026: [("01-01","New Year's Day"),("03-21","Human Rights Day"),("04-03","Good Friday"),("04-06","Family Day"),
        ("04-27","Freedom Day"),("05-01","Workers' Day"),("06-16","Youth Day"),("08-09","National Women's Day"),
        ("09-24","Heritage Day"),("12-16","Day of Reconciliation"),("12-25","Christmas Day"),("12-26","Day of Goodwill")],
 2027: [("01-01","New Year's Day"),("03-21","Human Rights Day"),("03-26","Good Friday"),("03-29","Family Day"),
        ("04-27","Freedom Day"),("05-01","Workers' Day"),("06-16","Youth Day"),("08-09","National Women's Day"),
        ("09-24","Heritage Day"),("12-16","Day of Reconciliation"),("12-25","Christmas Day"),("12-26","Day of Goodwill")],
}
EXTRA = [  # gazetted one-off days
 ("2026-11-04","Local Government Elections (Election Day)",
  "https://www.gov.za/news/media-statements/president-cyril-ramaphosa-declares-election-day",
  "Declared under s2A of the Public Holidays Act (Proclamation Notice 346 of 2026, GG 55352)"),
]
def build():
    out=[]
    for y,lst in BASE.items():
        for md,name in lst:
            d=dt.date.fromisoformat(f"{y}-{md}")
            out.append({"date":d.isoformat(),"name":name,"type":"public","source":GOV})
            if d.weekday()==6:
                out.append({"date":(d+dt.timedelta(days=1)).isoformat(),"name":name+" (observed)","type":"observed","source":GOV,"note":ACT})
    for d,name,src,note in EXTRA:
        out.append({"date":d,"name":name,"type":"special","source":src,"note":note})
    out.sort(key=lambda h:h["date"])
    return out
if __name__=="__main__":
    root=os.path.join(os.path.dirname(__file__),"..","data"); H=build()
    meta={"source":GOV,"checked":dt.date.today().isoformat(),"covers":f"{min(BASE)}-{max(BASE)}","holidays":H}
    json.dump(meta,open(os.path.join(root,"holidays.json"),"w"),indent=1,ensure_ascii=False)
    open(os.path.join(root,"holidays.js"),"w").write("// Auto-generated by tools/holidays.py\nwindow.HOLIDAYS = "+json.dumps(H,ensure_ascii=False)+";\n")
    for h in H: print(h["date"],dt.date.fromisoformat(h["date"]).strftime("%a"),h["name"])
